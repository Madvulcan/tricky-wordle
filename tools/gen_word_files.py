#!/usr/bin/env python3
"""Generate words-answers.js and words-guesses.js from tools/pool.txt.

Loud-failure validation contract (see docs/plans/2026-10-31-tricky-wordle.md):
- every answer is exactly 5 chars, A-Z only, unique
- every answer is in the guess dictionary OR tools/guess-overrides.txt
- tripwire (warning, not failure): word ends in S whose singular form is also in the pool
- output is deterministic: rotation order = sorted by sha256(word + SALT)
"""

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SALT = "tricky-wordle-v1-rotation-salt"


def fail(msg: str) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def main() -> None:
    pool_path = ROOT / "tools" / "pool.txt"
    dict_path = ROOT / "tools" / "guess-dictionary.txt"
    overrides_path = ROOT / "tools" / "guess-overrides.txt"

    words = [w.strip() for w in pool_path.read_text().splitlines() if w.strip()]
    pool = sorted(set(words))

    if len(words) != len(pool):
        seen, dupes = set(), []
        for w in words:
            if w in seen:
                dupes.append(w)
            seen.add(w)
        fail(f"duplicate words in pool.txt: {', '.join(sorted(set(dupes)))}")

    for w in pool:
        if len(w) != 5:
            fail(f"'{w}' is not 5 letters")
        if not w.isalpha() or not w.isupper() or not w.isascii():
            fail(f"'{w}' is not uppercase A-Z")

    guesses = {
        g.strip().upper()
        for g in dict_path.read_text().splitlines()
        if g.strip()
    }
    overrides = {
        o.strip().upper()
        for o in overrides_path.read_text().splitlines()
        if o.strip() and not o.strip().startswith("#")
    }

    unknown = sorted(w for w in pool if w not in guesses and w not in overrides)
    if unknown:
        fail(
            "answer(s) not in guess dictionary and not in guess-overrides.txt: "
            + ", ".join(unknown)
        )

    # Tripwire: singular-form words ending in S (VIRUS, FOCUS...) whose "plural"
    # heuristic misfires constantly, and genuine plural forms whose base is in the pool.
    # The heuristic is informational only; Jesse is the authority on what stays.
    plural_like = sorted(w for w in pool if w.endswith("S") and w[:-1] in pool)
    for w in plural_like:
        print(
            f"WARNING: '{w}' ends in S and its base form is also in the pool "
            "(check the no-plurals convention)",
            file=sys.stderr,
        )

    # Content-addressed rotation order: deterministic, decorrelated from alphabetical.
    rotation = sorted(pool, key=lambda w: hashlib.sha256((SALT + w).encode()).hexdigest())

    guesses_js = (
        "// GENERATED by tools/gen_word_files.py - do not edit by hand.\n"
        "// Full Wordle guess dictionary (tabatkins/wordle-list).\n"
        f"const WORDS_GUESSES = {json_js(sorted(guesses | overrides))};\n"
    )
    answers_js = (
        "// GENERATED by tools/gen_word_files.py - do not edit by hand.\n"
        f"// Curated answer pool: {len(pool)} words. ROTATION = daily serving order,\n"
        "// content-addressed (sha256(word+salt)) so appended words never re-order existing ones.\n"
        f"const WORDS_ANSWERS = {json_js(pool)};\n"
        f"const ROTATION = {json_js(rotation)};\n"
    )

    (ROOT / "words-guesses.js").write_text(guesses_js)
    (ROOT / "words-answers.js").write_text(answers_js)
    print(f"OK: {len(pool)} answers, {len(guesses | overrides)} guess words, rotation generated")

    # Human-readable reference sheet: full pool with the daily schedule for the next
    # 60 days. Lives at the repo root so it's easy to find (and shows up in ls).
    from datetime import date, timedelta

    EPOCH_DAY = date(2026, 11, 1)  # dayNumber epoch (must match game-logic.js)
    today = date.today()
    n0 = (today - EPOCH_DAY).days
    schedule = "\n".join(
        f"  {n0 + i + 1:>4}  {(EPOCH_DAY + timedelta(days=n0 + i)).strftime('%a %Y-%m-%d')}  {rotation[(n0 + i) % len(rotation)]}"
        for i in range(60)
    )
    sheet = (
        f"# Tricky Wordle - Answer Pool Reference\n"
        f"# Generated by tools/gen_word_files.py - do not edit by hand.\n"
        f"# {len(pool)} words. Source of truth: tools/pool.txt\n"
        f"#\n"
        f"# Daily schedule, next 60 days (game #N serves ROTATION[N-1], content-addressed):\n"
        f"{schedule}\n"
        f"\n# Full pool ({len(pool)} words, alphabetical):\n"
    )
    per_line = 12
    for i in range(0, len(pool), per_line):
        sheet += " ".join(f"{w:7}" for w in pool[i : i + per_line]) + "\n"
    (ROOT / "POOL-REFERENCE.txt").write_text(sheet)
    print(f"OK: POOL-REFERENCE.txt written ({len(pool)} words + 60-day schedule)")


def json_js(words: list) -> str:
    import json

    return json.dumps(words, separators=(",", ":"))


if __name__ == "__main__":
    main()
